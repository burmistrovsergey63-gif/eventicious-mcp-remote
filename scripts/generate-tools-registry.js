const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "src", "generated");
const OUT_FILE = path.join(OUT_DIR, "tools-registry.ts");

const transportPath = path.join(ROOT, "src", "mcp", "transport.ts");
const toolsDir = path.join(ROOT, "src", "tools");

const names = [];

const transportContent = fs.readFileSync(transportPath, "utf-8");
for (const m of transportContent.matchAll(/server\.tool\(\s*["']([^"']+)["']/g)) {
  names.push(m[1]);
}

for (const file of fs.readdirSync(toolsDir).filter((f) => f.endsWith(".ts"))) {
  const content = fs.readFileSync(path.join(toolsDir, file), "utf-8");
  for (const m of content.matchAll(/server\.tool\(\s*["']([^"']+)["']/g)) {
    names.push(m[1]);
  }
}

const unique = [...new Set(names)].sort();
const quoted = unique.map((n) => `  "${n}"`).join(",\n");

if (!fs.existsSync(OUT_DIR)) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

fs.writeFileSync(OUT_FILE, `// Auto-generated by scripts/generate-tools-registry.js\nexport const TOOL_NAMES: readonly string[] = [\n${quoted},\n] as const;\n`);
console.log(`Generated tools registry: ${unique.length} tools -> ${OUT_FILE}`);
